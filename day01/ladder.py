# ============================================================
# 第 6 关：循环（for）
# 为什么需要循环？因为"重复 100 次"这件事，人写 100 行，循环写 2 行
# range(1, 6) 的意思是：从 1 开始，到 6 之前停（所以是 1 2 3 4 5）
# ============================================================
print()
print("===== 第 6 关：循环 =====")

for i in range(1, 6):
    print("第", i, "次循环")

fruits = ["苹果", "香蕉", "橘子"]
for f in fruits:
    print("我喜欢吃", f)

total = 0
for i in range(1, 101):
    total = total + i
print("1 加到 100 =", total)


# ============================================================
# 第 7 关：嵌套循环（循环里面再套一个循环）
# 外层转 1 圈，内层要把所有圈转完 —— 这就是乘法表的结构
# ============================================================
print()
print("===== 第 7 关：嵌套循环 =====")

for i in range(1, 4):          # 外层：管"行"
    for j in range(1, 4):      # 内层：管"这一行里的每一列"
        print("*", end=" ")    # end=" " 表示打完不换行，改成打一个空格
    print()                    # 内层转完了，换行，准备打下一行

